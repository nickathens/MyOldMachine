def freshness(today=None):
    """Έλεγχος φρεσκάδας: ποια πεδία έχουν ξεπεράσει το όριο επαλήθευσης.

    Επιστρέφει λίστα με την ηλικία κάθε πεδίου σε ημέρες και σήμανση stale.
    Η ημερομηνία today δίνεται ρητά στους ελέγχους για ντετερμινισμό.
    """
    today = today or dt.date.today()
    rows = []
    for slug, d in DOMAINS.items():
        as_of = dt.date.fromisoformat(d["as_of"])
        age = (today - as_of).days
        rows.append({"pedio": slug, "as_of": d["as_of"], "ilikia_imeres": age,
                     "stale": age > STALE_DAYS})
    return rows


def _print_domain(slug, d):
    print(f"{d['titlos']}")
    print(f"  Επαλήθευση: {d['as_of']} {_VERIFY} στο πρωτογενές κείμενο πριν από χρήση")
    print(f"  Κατάσταση: {d['katastasi']}")
    print(f"  Για τον μηχανικό: {d['gia_ton_michaniko']}")
    print(f"  Πηγές: {'; '.join(d['piges'])}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    ls = sub.add_parser("list", help="Κατάλογος πεδίων")
    ls.add_argument("--json", action="store_true")

    sh = sub.add_parser("show", help="Πλήρης εικόνα πεδίου")
    sh.add_argument("pedio", nargs="?", help="Πεδίο, π.χ. nok")
    sh.add_argument("--all", action="store_true", help="Όλα τα πεδία")
    sh.add_argument("--json", action="store_true")

    fr = sub.add_parser("freshness", help="Ηλικία επαλήθευσης κάθε πεδίου")
    fr.add_argument("--json", action="store_true")

    args = ap.parse_args(argv)

    if args.cmd == "list":
        if args.json:
            print(json.dumps({k: v["titlos"] for k, v in DOMAINS.items()},
                             ensure_ascii=False, indent=2))
        else:
            print("Πεδία κανονιστικής επικαιρότητας:")
            for slug, d in DOMAINS.items():
                print(f"  {slug:<12} {d['titlos']} (επαλήθευση {d['as_of']})")
    elif args.cmd == "show":
        if args.all:
            if args.json:
                print(json.dumps(DOMAINS, ensure_ascii=False, indent=2))
            else:
                for slug, d in DOMAINS.items():
                    _print_domain(slug, d)
                    print()
        else:
            if not args.pedio:
                raise SystemExit("Δώσε πεδίο ή --all. Διαθέσιμα: " + ", ".join(DOMAINS))
            d = DOMAINS.get(args.pedio)
            if d is None:
                raise SystemExit(f"Άγνωστο πεδίο {args.pedio}. Διαθέσιμα: " + ", ".join(DOMAINS))
            if args.json:
                print(json.dumps(d, ensure_ascii=False, indent=2))
            else:
                _print_domain(args.pedio, d)
    elif args.cmd == "freshness":
        rows = freshness()
        if args.json:
            print(json.dumps(rows, ensure_ascii=False, indent=2))
        else:
            print(f"Φρεσκάδα επαλήθευσης (όριο {STALE_DAYS} ημέρες):")
            for r in rows:
                flag = "ΞΕΠΕΡΑΣΜΕΝΟ, θέλει επανεπαλήθευση" if r["stale"] else "εντός ορίου"
                print(f"  {r['pedio']:<12} {r['as_of']} ({r['ilikia_imeres']} ημέρες): {flag}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
