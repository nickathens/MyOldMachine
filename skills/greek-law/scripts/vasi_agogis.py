def normalize(text):
    """Accent and case fold Greek text, so a search matches regardless of tonos."""
    nfd = unicodedata.normalize("NFD", text)
    stripped = "".join(ch for ch in nfd if not unicodedata.combining(ch))
    return stripped.upper()


